from typing import TypedDict, NotRequired, Any


class InvestmentState(TypedDict):
    customer_id: str # Unique identifier for the customer in the database.
    query: str # The investment-related question or query posed by the user.

    intent: NotRequired[dict] # Query analysis result
    query_prompt_version: NotRequired[int] # Query analysis result

    customer: NotRequired[dict] # Customer profile data retrieved from the database (Customer Agent)

    knowledge: NotRequired[dict] # Retrieved knowledge for the query (Knowledge Agent)

    risk: NotRequired[dict] # Risk analysis result (Risk Agent)
    risk_prompt_version: NotRequired[int]

    portfolio: NotRequired[dict] # Structured portfolio analysis returned by Portfolio Agent.
    portfolio_prompt_version: NotRequired[int]

    compliance: NotRequired[dict]
    compliance_prompt_version: NotRequired[int]

    response: NotRequired[str] # response generated by the response agent
    status: NotRequired[str] # status of the response generation process
    response_prompt_version: NotRequired[int] # Version of the system prompt used for response generation

      
