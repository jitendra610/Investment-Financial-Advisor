
"""
Investment Advisor LangGraph State

Purpose:
1. Store user query and customer ID.
2. Store Query Analyzer results.
3. Store Planner decisions and selected agents.
4. Support conditional and parallel agent execution.
5. Store outputs from Customer, Knowledge, Risk,
   Portfolio, Compliance and Response Agents.
6. Support clarification for incomplete queries.
7. Track prompt versions and workflow status.
"""

from typing import TypedDict, NotRequired, Literal, Any


# Define possible workflow statuses.
WorkflowStatus = Literal[
    "pending",
    "needs_clarification",
    "in_progress",
    "needs_review",
    "completed",
    "failed",
]


# Define valid agent names for routing.
AgentName = Literal[
    "customer_agent",
    "knowledge_agent",
    "risk_agent",
    "portfolio_agent",
    "compliance_agent",
    "response_agent",
]


# Define the shared LangGraph workflow state.
class InvestmentState(TypedDict):

    # ----------------------------------------
    # 1. USER REQUEST INFORMATION
    # ----------------------------------------

    # Investment question submitted by the user.
    query: str

    # Customer identifier.
    # Optional because general questions do not
    # require customer-specific information.
    customer_id: NotRequired[str | None]

    # ----------------------------------------
    # 2. QUERY ANALYZER OUTPUT
    # ----------------------------------------

    # Classified intent of the user query.
    intent: NotRequired[str]

    # Information required to answer the query.
    required_information: NotRequired[list[str]]

    # Query Analyzer reasoning.
    reasoning: NotRequired[str]

    # Structured Query Analyzer output.
    # Contains intent, completeness, selected agents, etc.
    query_plan: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 3. PLANNER / ROUTER OUTPUT
    # ----------------------------------------

    # Agents selected for execution.
    # Example: ["customer_agent", "knowledge_agent"]
    selected_agents: NotRequired[list[AgentName]]

    # Whether the query requires additional information.
    requires_clarification: NotRequired[bool]

    # Clarification questions to ask the user.
    clarification_questions: NotRequired[list[str]]

    # Whether Risk Agent execution is required.
    requires_risk: NotRequired[bool]

    # Whether Portfolio Agent execution is required.
    requires_portfolio: NotRequired[bool]

    # Whether Compliance Agent execution is required.
    requires_compliance: NotRequired[bool]

    # ----------------------------------------
    # 4. CUSTOMER AGENT OUTPUT
    # ----------------------------------------

    # Customer financial profile retrieved from PostgreSQL.
    customer: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 5. KNOWLEDGE AGENT OUTPUT
    # ----------------------------------------

    # Retrieved RAG context and document sources.
    knowledge: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 6. RISK AGENT OUTPUT
    # ----------------------------------------

    # Customer risk assessment.
    risk: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 7. PORTFOLIO AGENT OUTPUT
    # ----------------------------------------

    # Portfolio analysis and allocation results.
    portfolio: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 8. COMPLIANCE AGENT OUTPUT
    # ----------------------------------------

    # Compliance evaluation and human review decision.
    compliance: NotRequired[dict[str, Any]]

    # ----------------------------------------
    # 9. RESPONSE AGENT OUTPUT
    # ----------------------------------------

    # Final response or clarification message.
    response: NotRequired[str]

    # Current workflow execution status.
    status: NotRequired[WorkflowStatus]

    # ----------------------------------------
    # 10. PROMPT VERSION TRACKING
    # ----------------------------------------

    # Query Agent prompt version metadata.
    query_prompt_version: NotRequired[dict[str, Any]]

    # Risk Agent prompt version metadata.
    risk_prompt_version: NotRequired[dict[str, Any]]

    # Portfolio Agent prompt version metadata.
    portfolio_prompt_version: NotRequired[dict[str, Any]]

    # Response Agent prompt version metadata.
    response_prompt_version: NotRequired[int | dict[str, Any]]

    # Ordered execution stages generated by Planner.
    execution_plan: NotRequired[list[dict[str, Any]]]
