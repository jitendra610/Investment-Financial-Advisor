# RAGAS function used to evaluate RAG application responses.
from ragas import evaluate

# SingleTurnSample: Stores one question, retrieved contexts,
# and the generated answer for evaluation.
# EvaluationDataset: Groups samples into an evaluation dataset
from ragas.dataset_schema import SingleTurnSample, EvaluationDataset
from ragas.metrics import Faithfulness, ResponseRelevancy

from langchain_openai import ChatOpenAI, OpenAIEmbeddings
from app.agents.llm import llm

# Evaluate the quality of a RAG-generated answer.
#
# Parameters:
# query: Original question asked by the user (string).
# contexts: Retrieved document chunks (list of strings).
# response: Answer generated by the RAG application (string).
#
# Returns:
# Dictionary containing Faithfulness and Response Relevancy scores.

def evaluate_answer(query, contexts, response):
    sample = SingleTurnSample(
        user_input=query,
        retrieved_contexts=contexts,
        response=response,
    )

    # Create an evaluation dataset containing one sample.
    # RAGAS supports evaluating multiple samples as well
    dataset = EvaluationDataset(samples=[sample])

    result = evaluate(
        dataset=dataset,
        metrics=[
            Faithfulness(),
            ResponseRelevancy(),
        ],
        llm=ChatOpenAI(
            model="gpt-4o-mini",
            temperature=0,
        ),
        embeddings=OpenAIEmbeddings(
            model="text-embedding-3-small"
        ),
    )

    return result.to_pandas().to_dict(
        orient="records"
    )[0]